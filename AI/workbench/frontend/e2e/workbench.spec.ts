test('native bridge initialization and real queue progress semantics', async ({page}) => {
  await page.addInitScript(() => {
    const fixture = {documents: [], busy: true, stage: 'Extracting synthetic document', bedrock: 'Connected', elapsed: 4,
      progress: {done: 1, total: 3}, key_configured: true, output_directory: 'Synthetic output',
      settings: {region: 'us-east-2', model: 'test', max_tokens: 16384, temperature: 0, document_limit: 100000}}
    Object.assign(window, {queueFixture: fixture})
    setTimeout(() => {
      window.pywebview = {api: {get_state: async () => ({ok: true, value: structuredClone(fixture)})}}
      window.dispatchEvent(new Event('pywebviewready'))
    }, 150)
  })
  await page.goto('/')
  const bar = page.getByLabel('Processing progress')
  await expect(bar).toHaveAttribute('value', '1')
  await expect(bar).toHaveAttribute('max', '3')
  await page.evaluate(() => Object.assign((window as unknown as {queueFixture: object}).queueFixture, {stage: 'Checking missing addresses: synthetic.pdf'}))
  await expect(bar).not.toHaveAttribute('value')
  await expect(page.locator('.progress-indicator')).toBeVisible()
  await page.evaluate(() => Object.assign((window as unknown as {queueFixture: object}).queueFixture, {busy: false, stage: 'Queue finished', progress: {done: 3, total: 3}}))
  await expect(bar).toHaveAttribute('value', '3')
  await expect(page.getByRole('button', {name: 'Open', exact: true})).toBeEnabled()
  await expect(page.getByText('Synthetic preview · no Bedrock calls')).toHaveCount(0)
})
