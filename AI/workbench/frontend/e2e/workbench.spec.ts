import { test, expect } from '@playwright/test'

test('group toggles retain edits, append once, and keep bottom controls visible', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/?preview=1')
  await page.getByRole('button', {name: 'Load examples'}).click()
  await expect(page.getByRole('heading', {name: 'AI PDF Reader'})).toBeVisible()
  await expect(page.getByRole('tab')).toHaveCount(0)
  await expect(page.locator('.sidebar, .document-table')).toHaveCount(0)
  const firstName = page.getByLabel('Claimant Information / First Name', {exact: true})
  await expect(firstName).toHaveValue('Avery')
  await firstName.fill('Avery edited')
  const settings = page.getByRole('button', {name: 'Settings', exact: true})
  await settings.click()
  await expect(page.getByRole('region', {name: 'Settings group'})).toBeInViewport()
  await page.getByLabel('AWS region').fill('us-west-2')
  await page.getByLabel('Bedrock API key').fill('synthetic-test-key')
  await settings.click()
  await expect(page.locator('#group-Settings')).toBeHidden()
  await settings.click()
  await expect(page.locator('#group-Settings')).toHaveCount(1)
  await expect(page.getByLabel('AWS region')).toHaveValue('us-west-2')
  await expect(page.getByLabel('Bedrock API key')).toHaveValue('synthetic-test-key')
  await expect(firstName).toHaveValue('Avery edited')
  await page.getByRole('button', {name: 'Output', exact: true}).click()
  await expect(page.getByRole('region', {name: 'Output group'})).toBeInViewport()
  expect(await page.locator('.extra-group').evaluateAll(groups => groups.map(g => g.id))).toEqual(['group-Settings', 'group-Output'])
  await page.getByRole('button', {name: 'Fields', exact: true}).click()
  await expect(firstName).toBeInViewport()
  await page.getByRole('button', {name: 'Save field changes (1)'}).click()
  await expect(page.getByRole('button', {name: 'Save field changes', exact: true})).toBeDisabled()
  await expect(firstName).toHaveValue('Avery edited')
  await expect(page.getByLabel('Processing progress')).toHaveAttribute('value', '2')
  await page.screenshot({path: '../test-results/compact-form-480x900.png'})
  for (const height of [561, 861, 1061]) {
    await page.setViewportSize({width: 464, height})
    await page.getByRole('button', {name: 'Settings', exact: true}).click()
    await expect(page.getByRole('navigation', {name: 'Form navigation'})).toBeInViewport({ratio: 1})
    await expect(page.getByRole('button', {name: 'Save field changes', exact: true})).toBeInViewport({ratio: 1})
    await expect(page.getByLabel('Processing progress')).toBeInViewport({ratio: 1})
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    expect(await page.locator('main').evaluate(el => el.scrollWidth <= el.clientWidth)).toBeTruthy()
  }
  await page.setViewportSize({width: 464, height: 561})
  await page.getByRole('button', {name: 'Fields', exact: true}).click()
  await page.screenshot({path: '../test-results/compact-form-480x600.png'})
  expect(errors).toEqual([])
})

