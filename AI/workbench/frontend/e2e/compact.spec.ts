import { test, expect } from '@playwright/test'

test('compact strip reuses progress, supports keyboard, restores edits and scroll', async ({page}) => {
  await page.goto('/?preview=1')
  await page.getByRole('button', {name: 'Load examples'}).click()
  const field = page.getByLabel('Claimant Information / First Name', {exact: true})
  await field.fill('Synthetic edited')
  await page.getByRole('button', {name: 'Settings', exact: true}).click()
  await page.getByLabel('AWS region').fill('us-west-2')
  const scroll = await page.locator('main').evaluate(el => el.scrollTop)
  const toggle = page.getByRole('button', {name: 'Enter compact mode'})
  await toggle.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toBeHidden()
  await page.setViewportSize({width: 464, height: 101})
  await expect(page.getByLabel('Processing progress')).toBeInViewport({ratio: 1})
  await expect(page.locator('.processing-status')).toBeInViewport({ratio: 1})
  await expect(page.locator('.processing-status')).toHaveCount(1)
  await expect(page.getByLabel('Processing progress')).toHaveCount(1)
  await expect(page.getByRole('navigation')).toBeHidden()
  const sizes = await page.evaluate(() => Object.fromEntries(
    ['.app-header', '.processing-status', '.progress-wrap', '.bottom-dock'].map(s => [s, document.querySelector(s)!.getBoundingClientRect().height])))
  console.log('Compact CSS pixel measurements:', JSON.stringify(sizes))
  expect(sizes['.app-header'] + sizes['.bottom-dock']).toBeLessThanOrEqual(101)
  await page.setViewportSize({width: 464, height: 861})
  await page.getByRole('button', {name: 'Exit compact mode'}).press('Enter')
  await expect(page.locator('main')).toBeVisible()
  await expect(field).toHaveValue('Synthetic edited')
  await expect(page.getByLabel('AWS region')).toHaveValue('us-west-2')
  await expect.poll(() => page.locator('main').evaluate(el => el.scrollTop)).toBe(scroll)
})
